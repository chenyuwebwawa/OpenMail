// ---------- Modal ----------
export function modal({ title, body, footer, wide = false, onClose }) {
  const mask = document.createElement('div');
  mask.className = 'modal-mask';
  mask.innerHTML = `
    <div class="modal ${wide ? 'wide' : ''}">
      <div class="modal-head"><h3>${esc(title)}</h3><button class="btn btn-ghost btn-icon" data-close>${icon('x')}</button></div>
      <div class="modal-body">${body}</div>
      ${footer ? `<div class="modal-foot">${footer}</div>` : ''}
    </div>`;
  const close = () => { mask.remove(); onClose && onClose(); };
  mask.addEventListener('click', e => { if (e.target === mask || e.target.closest('[data-close]')) close(); });
  document.body.appendChild(mask);
  return { mask, close, el: mask.querySelector('.modal') };
}

// ---------- 主题 ----------
export function initTheme() {
  const t = localStorage.getItem('om_theme') || 'light';
  document.documentElement.setAttribute('data-theme', t);
  return t;
}
export function toggleTheme() {
  const cur = document.documentElement.getAttribute('data-theme') || 'light';
  const next = cur === 'light' ? 'dark' : 'light';
  document.documentElement.setAttribute('data-theme', next);
  localStorage.setItem('om_theme', next);
  return next;
}
