// API 客户端 + 通用工具
export const API = {
  token: localStorage.getItem('om_token') || '',
  user: JSON.parse(localStorage.getItem('om_user') || 'null'),

  async req(method, path, body) {
    const res = await fetch('/api' + path, {
      method,
      headers: {
        'Content-Type': 'application/json',
        ...(API.token ? { Authorization: `Bearer ${API.token}` } : {}),
      },
      body: body !== undefined ? JSON.stringify(body) : undefined,
    });
    let json = {};
    try { json = await res.json(); } catch {}
    if (res.status === 401 && !path.startsWith('/auth/')) {
      localStorage.removeItem('om_token');
      localStorage.removeItem('om_user');
      API.token = '';
      API.user = null;
      if (location.hash.startsWith('#/login')) {
        location.reload(); // 已在登录路由时强制重绘，避免残留旧界面
      } else {
        location.hash = '#/login';
      }
      throw new Error(json.error || '请重新登录');
    }
    if (!res.ok) throw new Error(json.error || `请求失败 (${res.status})`);
    return json;
  },
  get(p) { return API.req('GET', p); },
  post(p, b) { return API.req('POST', p, b); },
  put(p, b) { return API.req('PUT', p, b); },
  patch(p, b) { return API.req('PATCH', p, b); },
  del(p) { return API.req('DELETE', p); },

  setAuth(token, user) {
    API.token = token;
    API.user = user;
    localStorage.setItem('om_token', token);
    localStorage.setItem('om_user', JSON.stringify(user));
  },
  logout() {
    API.post('/auth/logout').catch(() => {});
    API.token = '';
    API.user = null;
    localStorage.removeItem('om_token');
    localStorage.removeItem('om_user');
  },
};

// ---------- Toast ----------
export function toast(msg, type = '') {
  const el = document.createElement('div');
  el.className = 'toast ' + type;
  el.textContent = msg;
  document.getElementById('toast-wrap').appendChild(el);
  setTimeout(() => { el.style.opacity = '0'; el.style.transition = 'opacity .3s'; }, 2600);
  setTimeout(() => el.remove(), 3000);
}

